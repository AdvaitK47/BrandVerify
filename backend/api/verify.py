
"""
Pre-Flight Compliance Verification Endpoints.

Text findings are generated by deterministic rules.
AI explains those findings but does not decide the score.
"""

from fastapi import APIRouter, HTTPException, UploadFile, File, Form
from fastapi.concurrency import run_in_threadpool
from typing import Optional
import logging
import os
import tempfile
import uuid
from pathlib import Path

from backend.config import settings
from backend.db import save_scan
from backend.models.scan import ScanRequest, ScanResult
from backend.services.text_verifier import verify_text_compliance
from backend.services.ai_explainer import explain_findings
from backend.services.image_verifier import verify_image_compliance
from backend.services.doc_extractor import SUPPORTED_EXTENSIONS, DocumentError
from backend.services.doc_verifier import verify_document
from backend.services.audio_verifier import verify_audio_compliance
from backend.services.video_verifier import verify_video_compliance

router = APIRouter()
logger = logging.getLogger(__name__)


def calculate_compliance_score(flags) -> int:
    """
    Calculate a transparent preliminary score from finding severity.

    Informational notes do not reduce the score.
    This is a product heuristic, not a legal compliance measurement.
    """
    deductions = {
        "critical": 30,
        "high": 20,
        "warning": 15,
        "medium": 15,
        "low": 5,
        "info": 0,
        "informational": 0,
    }

    total_deduction = 0

    for flag in flags:
        severity = getattr(flag, "severity", "info")
        severity = getattr(severity, "value", severity)
        severity_name = str(severity).lower()
        total_deduction += deductions.get(severity_name, 0)

    return max(0, min(100, 100 - total_deduction))


def determine_overall_status(flags) -> str:
    """
    One rule for every endpoint: "warnings_detected" if any flag is more
    serious than info, otherwise "compliant".
    """
    for flag in flags:
        severity = getattr(flag, "severity", "info")
        severity = getattr(severity, "value", severity)
        if str(severity).lower() not in ("info", "informational"):
            return "warnings_detected"
    return "compliant"


@router.post("/text", response_model=ScanResult)
async def verify_text_endpoint(payload: ScanRequest):
    """Scan text with deterministic rules and explain findings with AI."""

    if not payload.raw_text or not payload.raw_text.strip():
        raise HTTPException(
            status_code=400,
            detail="raw_text field is required for text verification",
        )

    diff_result = verify_text_compliance(
        payload.raw_text,
        payload.custom_rule,
    )

    score = calculate_compliance_score(diff_result.flags)

    ai_explanation = explain_findings(
        payload.raw_text,
        diff_result.flags,
    )

    result = ScanResult(
        scan_id=f"scan-{uuid.uuid4().hex[:8]}",
        brand_id=payload.brand_id,
        content_type="text",
        title=payload.title,
        target_channel=payload.target_channel,
        overall_status=determine_overall_status(diff_result.flags),
        compliance_score=score,
        flags=diff_result.flags,
        ai_explanation=ai_explanation,
        diff=diff_result,
    )

    try:
        await run_in_threadpool(save_scan, result)
    except Exception:
        logger.exception("Could not save scan %s", result.scan_id)

    return result


@router.post("/upload")
async def verify_file_upload(
    brand_id: str = Form(...),
    content_type: str = Form(...),
    title: str = Form(...),
    target_channel: str = Form(...),
    custom_rule: Optional[str] = Form(None),
    file: UploadFile = File(...),
):
    """Upload and verify binary creative assets."""

    if content_type == "document":
        return await _verify_document_upload(
            brand_id, title, target_channel, custom_rule, file
        )

    if content_type == "image":
        flags = verify_image_compliance(
            file.filename,
            ["#ffffff", "#a1a1aa", "#121214"],
            custom_rule,
        )
    elif content_type == "audio":
        flags = verify_audio_compliance(file.filename, custom_rule)
    elif content_type == "video":
        flags = verify_video_compliance(file.filename, custom_rule)
    else:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported content_type: {content_type}",
        )

    score = calculate_compliance_score(flags)

    return {
        "scan_id": f"scan-{uuid.uuid4().hex[:8]}",
        "brand_id": brand_id,
        "content_type": content_type,
        "filename": file.filename,
        "title": title,
        "target_channel": target_channel,
        "overall_status": determine_overall_status(flags),
        "compliance_score": score,
        "flags": flags,
    }


async def _verify_document_upload(
    brand_id: str,
    title: str,
    target_channel: str,
    custom_rule: Optional[str],
    file: UploadFile,
) -> ScanResult:
    """Validate, read and scan an uploaded .pdf/.docx, then save the result."""

    extension = Path(file.filename or "").suffix.lower()
    if extension not in SUPPORTED_EXTENSIONS:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Unsupported document type '{extension or 'unknown'}'. "
                f"Supported: {', '.join(sorted(SUPPORTED_EXTENSIONS))}."
            ),
        )

    max_bytes = settings.MAX_UPLOAD_MB * 1024 * 1024
    tmp_path = None

    try:
        # Stream to a temp file so a huge upload is never held fully in memory.
        with tempfile.NamedTemporaryFile(suffix=extension, delete=False) as tmp:
            tmp_path = tmp.name
            size = 0
            while True:
                chunk = await file.read(1024 * 1024)
                if not chunk:
                    break
                size += len(chunk)
                if size > max_bytes:
                    raise HTTPException(
                        status_code=413,
                        detail=f"File is larger than {settings.MAX_UPLOAD_MB} MB.",
                    )
                tmp.write(chunk)

        try:
            scan = await run_in_threadpool(
                verify_document, tmp_path, custom_rule, file.filename
            )
        except DocumentError as exc:
            raise HTTPException(status_code=422, detail=str(exc))
    finally:
        if tmp_path and os.path.exists(tmp_path):
            os.unlink(tmp_path)

    explanation = await run_in_threadpool(explain_findings, scan.text, scan.flags)

    result = ScanResult(
        scan_id=f"scan-{uuid.uuid4().hex[:8]}",
        brand_id=brand_id,
        content_type="document",
        title=title,
        target_channel=target_channel,
        overall_status=determine_overall_status(scan.flags),
        compliance_score=calculate_compliance_score(scan.flags),
        flags=scan.flags,
        ai_explanation=explanation,
        diff=None,
    )

    try:
        await run_in_threadpool(save_scan, result)
    except Exception:
        logger.exception("Could not save scan %s", result.scan_id)

    return result
